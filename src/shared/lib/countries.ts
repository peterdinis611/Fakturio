const byCode = new Map(COUNTRIES.map((c) => [c.code, c]));

export function getCountry(code: string | null | undefined) {
  if (!code) return undefined;
  return byCode.get(code.trim().toUpperCase());
}

export function countryLabel(code: string | null | undefined) {
  return getCountry(code)?.name ?? code ?? "";
}

export function countryDial(code: string | null | undefined) {
  return getCountry(code)?.dial ?? "+421";
}

export function countriesForSelect() {
  const priority = new Set<string>(["SK", "CZ", "AT", "HU", "PL", "DE"]);
  const head = ["SK", "CZ", "AT", "HU", "PL", "DE"]
    .map((code) => byCode.get(code))
    .filter(Boolean) as CountryOption[];
  const rest = COUNTRIES.filter((c) => !priority.has(c.code)).sort((a, b) =>
    a.name.localeCompare(b.name, "sk"),
  );
  return [...head, ...rest];
}
